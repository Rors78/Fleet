def _fleet_size() -> int:
    """Pollable fleet members, from the one source of truth.

    These strings become the live Telegram channel descriptions, so a
    hardcoded count is a subscriber-facing claim that goes stale silently —
    the same defect as the "19 bots · live" literal on the signal cards
    (fixed 2026-08-05). It said 16 while the roster had 18.

    Falls back to 18 only if the registry is unavailable; that is a wrong
    number in a failure case, but the alternative is a broken publish.
    """
    if bot_registry_list is None:
        return 18
    try:
        return len(bot_registry_list()) or 18
    except Exception:
        return 18


def _pair_count() -> int:
    """Trading pairs in the live universe. Same reasoning as _fleet_size():
    this is subscriber-facing copy, and the hardcoded 47 was stale (50 live).
    """
    try:
        import os
        u = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                        "universe.json"), encoding="utf-8"))
        n = u.get("count")
        if isinstance(n, int) and n > 0:
            return n
        pairs = u.get("pairs")
        if isinstance(pairs, (list, dict)) and pairs:
            return len(pairs)
    except Exception:
        pass
    return 50


