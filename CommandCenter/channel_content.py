def send_message(chat_id: str, text: str, pin: bool = False) -> dict | None:
    """Send a Telegram message and optionally pin it."""
    url = f"https://api.telegram.org/bot{TOKEN}/sendMessage"
    payload = json.dumps({
        "chat_id": chat_id,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }).encode("utf-8")
    try:
        req = urllib.request.Request(url, data=payload,
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=15) as resp:
            result = json.loads(resp.read())
            msg_id = result.get("result", {}).get("message_id")
            print(f"  ✓ Sent (msg_id={msg_id})")

            if pin and msg_id:
                time.sleep(1)
                pin_url = f"https://api.telegram.org/bot{TOKEN}/pinChatMessage"
                pin_payload = json.dumps({
                    "chat_id": chat_id,
                    "message_id": msg_id,
                    "disable_notification": True,
                }).encode("utf-8")
                pin_req = urllib.request.Request(pin_url, data=pin_payload,
                                                 headers={"Content-Type": "application/json"})
                urllib.request.urlopen(pin_req, timeout=10)
                print(f"  📌 Pinned")

            return result
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        print(f"  ✗ HTTP {e.code}: {body[:200]}")
        return None
    except Exception as e:
        print(f"  ✗ Error: {e}")
        return None


def set_description(chat_id: str, description: str) -> bool:
    """Set a channel's description."""
    url = f"https://api.telegram.org/bot{TOKEN}/setChatDescription"
    payload = json.dumps({
        "chat_id": chat_id,
        "description": description,
    }).encode("utf-8")
    try:
        req = urllib.request.Request(url, data=payload,
                                     headers={"Content-Type": "application/json"})
        urllib.request.urlopen(req, timeout=10)
        print(f"  ✓ Description set")
        return True
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        print(f"  ✗ HTTP {e.code}: {body[:200]}")
        return False
    except Exception as e:
        print(f"  ✗ Error: {e}")
        return False


